#pragma once

// IEphemeris — абстрактный интерфейс провайдера позиций небесных тел.
//
// ООП-приёмы: АБСТРАКЦИЯ + основа паттерна СТРАТЕГИЯ. Остальная программа
// (SolarSystem, тела) знает только этот интерфейс и не подозревает, откуда
// берутся координаты — из libnova, из собственного решателя Кеплера или из
// CSPICE. Конкретный провайдер подменяется в рантайме, не затрагивая клиентов.

#include "math/Vec3.hpp"

namespace solar {

// Идентификаторы тел, для которых провайдер умеет считать гелиоцентрическую
// позицию. Солнце — начало координат. Луна не входит: её положение задаётся
// относительно родителя и вычисляется самим классом Moon.
enum class BodyId {
    Sun,
    Mercury,
    Venus,
    Earth,
    Mars,
    Jupiter,
    Saturn,
    Uranus,
    Neptune
};

class IEphemeris {
public:
    virtual ~IEphemeris() = default;

    // Гелиоцентрическая позиция тела в эклиптических декартовых координатах
    // (а.е.) на заданную юлианскую дату. Для Солнца — (0,0,0).
    virtual Vec3 heliocentricPosition(BodyId body, double julianDay) const = 0;

    // Геоцентрическая эклиптическая позиция Луны (а.е.) — смещение от центра
    // Земли. Опциональная возможность: провайдер, который её не умеет, может
    // не переопределять метод (по умолчанию нулевой вектор). Так интерфейс
    // остаётся пригодным для любых стратегий.
    virtual Vec3 moonGeocentricPosition(double /*julianDay*/) const { return Vec3{}; }

    // Человекочитаемое имя провайдера (для UI выбора стратегии).
    virtual const char* providerName() const = 0;
};

} // namespace solar
